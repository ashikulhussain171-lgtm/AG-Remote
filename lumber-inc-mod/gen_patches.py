#!/usr/bin/env python3
"""Generate menu/src/com/panther/mod/Patches.java (runtime patch table) from the measured
Lumber Inc 1.13.3 arm64 libil2cpp.so. Every original byte string is read from the real file,
so the menu can refuse to patch any other build."""
import hashlib, os, sys
from keystone import Ks, KS_ARCH_ARM64, KS_MODE_LITTLE_ENDIAN
import patch_libil2cpp as P

ks = Ks(KS_ARCH_ARM64, KS_MODE_LITTLE_ENDIAN)
def asm(src, rva): return bytes(ks.asm(src, rva)[0])

# group -> [(label, rva, new bytes)]
def groups():
    g = {
        "CURRENCY": [(name, rva, P.body(rva, field, kinds)) for name, rva, size, field, kinds in P.TARGETS],
        "FREE_SPEND": [
            # IsSpendable = amount >= cost  ->  IsSpendable = true   (cset w1, ge)
            ("RuntimeResourceSpendable_Basic.RefreshIsSpendable+0x1F0", 0x3156484, asm("mov w1, #1", 0x3156484)),
            ("ConstructionResource.DoRemoveAmount", 0x312C178, asm("ret", 0x312C178)),
            ("SupervisorCardResource.DoRemoveAmount", 0x2EEFF8C, asm("ret", 0x2EEFF8C)),
        ],
        "MAX_LEVEL": [
            # Upgradable<object>.IUpgradable.Upgrade (shared by every Upgradable_v2 level type):
            #   ldr w22,[x19,#0x28] = current index; w0 = max index from the level provider.
            #   cmp w22, w0  ->  subs w22, w22, w0   (same flags, keeps cur-max in callee-saved w22)
            #   add w8, w8, #1  ->  sub w8, w8, w22  (new index = cur - (cur - max) = max)
            ("Upgradable.Upgrade cmp", 0x4183BB0, asm("subs w22, w22, w0", 0x4183BB0)),
            ("Upgradable.Upgrade +1", 0x4183C34, asm("sub w8, w8, w22", 0x4183C34)),
            #   UpdateCachedLevels(isUpgrade: true) promotes the cached next level (old index + 1) to current,
            #   so the jump showed as +1. isUpgrade: false re-provides current/next from the new index
            #   (same call SetCurrentLevel makes).   mov w1, #1  ->  mov w1, wzr
            ("Upgradable.Upgrade isUpgrade", 0x4183C2C, asm("mov w1, wzr", 0x4183C2C)),
        ],
        "NO_ADS": [
            ("Mediation.get_AdFree", 0x2A8F79C, asm("mov w0, #1; ret", 0x2A8F79C)),
            ("AdsFreeManager.get_IsAdFree", 0x355D994, asm("mov w0, #1; ret", 0x355D994)),
            ("Store.get_ShouldShowAds", 0x34C1E4C, asm("mov w0, wzr; ret", 0x34C1E4C)),
        ],
    }
    return g

def main(so_path, out_java):
    data = open(so_path, 'rb').read()
    assert hashlib.sha256(data).hexdigest() == P.EXPECTED_SHA256, "not the measured 1.13.3 libil2cpp.so"
    lines = []
    for grp, items in groups().items():
        for label, rva, new in items:
            off = rva - P.TEXT_VA + P.TEXT_OFF
            orig = data[off:off + len(new)]
            assert orig != new, label
            lines.append(f'        new Patch(Group.{grp}, "{label}", 0x{rva:X}L, "{orig.hex()}", "{new.hex()}"),')
    src = f'''package com.panther.mod;

// Generated by gen_patches.py from libil2cpp.so sha256 {P.EXPECTED_SHA256}
// (Lumber Inc 1.13.3, arm64-v8a). RVA = offset from the module's load base.
final class Patches {{
    enum Group {{ CURRENCY, FREE_SPEND, MAX_LEVEL, NO_ADS }}

    static final class Patch {{
        final Group group; final String name; final long rva; final byte[] orig; final byte[] patched;
        Patch(Group g, String n, long r, String o, String p) {{ group = g; name = n; rva = r; orig = hex(o); patched = hex(p); }}
    }}

    static byte[] hex(String s) {{
        byte[] b = new byte[s.length() / 2];
        for (int i = 0; i < b.length; i++) b[i] = (byte) Integer.parseInt(s.substring(2 * i, 2 * i + 2), 16);
        return b;
    }}

    static final long MODULE_SIZE_MIN = 0x{P.TEXT_VA + P.TEXT_SZ:X}L;

    static final Patch[] ALL = {{
{chr(10).join(lines)}
    }};
}}
'''
    os.makedirs(os.path.dirname(out_java), exist_ok=True)
    open(out_java, 'w').write(src)
    print(src)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
