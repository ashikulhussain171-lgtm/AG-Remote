#!/usr/bin/env python3
"""Generate menu/src/com/panther/mod/Patches.java for Granny: Chapter Two 1.2.8
(com.dvloper.grannychaptertwo, arm64-v8a). Original bytes are read from the real libil2cpp.so,
so the menu refuses any other build."""
import hashlib, os, sys
from keystone import Ks, KS_ARCH_ARM64, KS_MODE_LITTLE_ENDIAN

EXPECTED_SHA256 = "d9f316b79008ff6d76e9011f9f5e7d194d7e7447e4363f293b93202c178ef7ec"
# R E segment: vaddr 0x1068570, file offset 0x1064570, size 0x1a1c5b0 (file offset = RVA - 0x4000)
TEXT_VA, TEXT_OFF, TEXT_SZ = 0x1068570, 0x1064570, 0x1A1C5B0

ks = Ks(KS_ARCH_ARM64, KS_MODE_LITTLE_ENDIAN)
def asm(src, rva): return bytes(ks.asm(src, rva)[0])
RET = "ret"

GROUPS = [
    ("GOD_MODE", "God Mode", [
        # EnemyAIGranny.FixedUpdate: if (distance < attackDistance && seePlayer && ...) catch player.
        #   0x130F778 ldr s0,[x19,#0x170]; ldr s1,[x19,#0x174]; fcmp; b.pl skip  ->  b skip
        ("EnemyAIGranny.FixedUpdate catch check", 0x130F784, asm("b #0x130F7B8", 0x130F784)),
        # EnemyAIGrandpa.FixedUpdate: distance 0x210 vs attackDistance 0x214, same shape
        ("EnemyAIGrandpa.FixedUpdate catch check", 0x130710C, asm("b #0x1307138", 0x130710C)),
    ]),
    ("BLIND", "Invisible (no sight)", [
        ("EnemyEye.Update", 0x1381C94, asm(RET, 0x1381C94)),            # sets EnemyAIGranny.seePlayer
        ("EnemyEyeGranpa.Update", 0x13821DC, asm(RET, 0x13821DC)),
        ("grannySeePlayerTrigger.OnTriggerStay", 0x1384B04, asm(RET, 0x1384B04)),
    ]),
    ("SILENT", "Silent (no hearing)", [
        ("GrannyHear.OnTriggerEnter", 0x1383C58, asm(RET, 0x1383C58)),
    ]),
    ("FREEZE", "Freeze Granny + Grandpa", [
        ("EnemyAIGranny.FixedUpdate", 0x130D6BC, asm(RET, 0x130D6BC)),
        ("EnemyAIGrandpa.FixedUpdate", 0x1305894, asm(RET, 0x1305894)),
    ]),
    ("NO_ADS", "No Ads", [
        ("MaxSdkAndroid.ShowInterstitial", 0x2023F48, asm(RET, 0x2023F48)),
    ]),
]

def main(so_path, out_java):
    data = open(so_path, 'rb').read()
    assert hashlib.sha256(data).hexdigest() == EXPECTED_SHA256, "not the measured Granny 1.2.8 libil2cpp.so"
    lines, groups, labels = [], [], []
    for gname, label, items in GROUPS:
        groups.append(gname); labels.append(f'{{ Group.{gname}, "{label}" }}')
        for name, rva, new in items:
            assert TEXT_VA <= rva < TEXT_VA + TEXT_SZ, name
            off = rva - TEXT_VA + TEXT_OFF
            orig = data[off:off + len(new)]
            assert orig != new, name
            lines.append(f'        new Patch(Group.{gname}, "{name}", 0x{rva:X}L, "{orig.hex()}", "{new.hex()}"),')
    src = f'''package com.panther.mod;

// Generated by gen_patches.py from libil2cpp.so sha256 {EXPECTED_SHA256}
// (Granny: Chapter Two 1.2.8, arm64-v8a). RVA = offset from the module's load base.
final class Patches {{
    enum Group {{ {", ".join(groups)} }}

    static final class Patch {{
        final Group group; final String name; final long rva; final byte[] orig; final byte[] patched;
        Patch(Group g, String n, long r, String o, String p) {{ group = g; name = n; rva = r; orig = hex(o); patched = hex(p); }}
    }}

    static byte[] hex(String s) {{
        byte[] b = new byte[s.length() / 2];
        for (int i = 0; i < b.length; i++) b[i] = (byte) Integer.parseInt(s.substring(2 * i, 2 * i + 2), 16);
        return b;
    }}

    static final long MODULE_SIZE_MIN = 0x{TEXT_VA + TEXT_SZ:X}L;

    /** Menu switches, in display order. */
    static final Object[][] ITEMS = {{
        {(","+chr(10)+"        ").join(labels)}
    }};

    static final Patch[] ALL = {{
{chr(10).join(lines)}
    }};
}}
'''
    os.makedirs(os.path.dirname(out_java), exist_ok=True)
    open(out_java, 'w').write(src)
    print(src)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
